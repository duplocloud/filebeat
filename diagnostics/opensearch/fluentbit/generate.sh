#!/usr/bin/env bash
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RBAC_TPL="${DIR}/rbac/rbac.yaml.tpl"
K8S_TPL="${DIR}/ds/fluentbit-k8s.yaml.tpl"

if [ -t 1 ]; then R='\033[0;31m' G='\033[0;32m' B='\033[1m' Z='\033[0m'
else R='' G='' B='' Z=''; fi
err() { echo -e "${R}Error:${Z} $1" >&2; exit 1; }

# Optional --cluster-wide flag
CLUSTER_WIDE=false
if [[ "${1:-}" == "--cluster-wide" ]]; then
    CLUSTER_WIDE=true
    shift
fi

# Kubernetes namespace (full namespace, e.g. duploservices-dev-usw2)
NAMESPACE="${1:-}"
[ -z "$NAMESPACE" ] && read -rp "Enter the K8s namespace (e.g. duploservices-dev-usw2): " NAMESPACE
NAMESPACE="$(echo "$NAMESPACE" | tr -d '[:space:]' | tr '[:upper:]' '[:lower:]')"
[ -z "$NAMESPACE" ] && err "Namespace cannot be empty."
[[ ! "$NAMESPACE" =~ ^[a-z][a-z0-9-]*$ ]] && err "Must be lowercase alphanumeric/hyphens, starting with a letter."

# Docker image
IMAGE="${2:-}"
[ -z "$IMAGE" ] && read -rp "Docker image (e.g. duplocloud/fluentbit:4.2.4-70db2f7...): " IMAGE
[ -z "$IMAGE" ] && err "Docker image cannot be empty."

# ES host - strip scheme, port, and trailing slash to get bare hostname
EHOST="${3:-}"
[ -z "$EHOST" ] && read -rp "Elastic/OpenSearch host (e.g. system-svc-es-oc-default.myapps.duplocloud.net): " EHOST
[ -z "$EHOST" ] && err "Elastic host cannot be empty."
EHOST="$(echo "$EHOST" | sed -E 's|^https?://||; s|:[0-9]+/?$||; s|/$||')"

# Check templates exist
[ ! -f "$RBAC_TPL" ] && err "Template not found: ${RBAC_TPL}"
[ ! -f "$K8S_TPL" ] && err "Template not found: ${K8S_TPL}"

# Mode-dependent values
if $CLUSTER_WIDE; then
    DEPLOY_NAME="cluster"
    TENANT_LOCAL="False"
else
    DEPLOY_NAME="$NAMESPACE"
    TENANT_LOCAL="True"
fi

# Generate RBAC
RBAC_OUT="${DIR}/rbac/rbac-${DEPLOY_NAME}.yaml"
sed -e "s|{{NAMESPACE}}|${NAMESPACE}|g" \
    -e "s|{{DEPLOY_NAME}}|${DEPLOY_NAME}|g" "$RBAC_TPL" > "$RBAC_OUT"

# Generate DaemonSet YAML — first pass: simple sed placeholders
K8S_OUT="${DIR}/ds/fluentbit-k8s-${DEPLOY_NAME}.yaml"
sed -e "s|{{NAMESPACE}}|${NAMESPACE}|g" \
    -e "s|{{DEPLOY_NAME}}|${DEPLOY_NAME}|g" \
    -e "s|{{DOCKER_IMAGE}}|${IMAGE}|g" \
    -e "s|{{ES_HOST}}|${EHOST}|g" \
    -e "s|{{TENANT_LOCAL}}|${TENANT_LOCAL}|g" "$K8S_TPL" > "$K8S_OUT"

# Second pass: replace multi-line block placeholders.
# Write to a temp file and move, avoiding sed -i portability issues (BSD vs GNU).
TMP_OUT="${K8S_OUT}.tmp"
if $CLUSTER_WIDE; then
    # Remove the nodeSelector tenant line; replace tolerations with catch-all
    sed -e '/{{NODE_SELECTOR_TENANT}}/d' \
        -e 's|^{{TOLERATIONS}}$|      tolerations:\
        - operator: Exists|' "$K8S_OUT" > "$TMP_OUT"
else
    # Replace nodeSelector tenant placeholder; replace tolerations with spot-only
    sed -e "s|{{NODE_SELECTOR_TENANT}}|        tenantname: ${NAMESPACE}|" \
        -e 's|^{{TOLERATIONS}}$|      tolerations:\
        - effect: NoExecute\
          key: duplocloud.net/spot-instance\
          operator: Exists|' "$K8S_OUT" > "$TMP_OUT"
fi
mv "$TMP_OUT" "$K8S_OUT"

# ---------------------------------------------------------------------------
# Per-tenant filter ConfigMap (mounted at /fluent-bit/etc/conf.d)
#
# Filebeat lets a pod request custom processing via
# co.elastic.logs/processors.<N>.<type>.<key> annotations. Fluent Bit has no
# equivalent, so the processing is expressed as [FILTER] blocks instead.
#
# Scope is the whole namespace, with exceptions excluded by negative lookahead.
# Enumerating annotated services does not scale: at 100 services every new
# deployment would need a platform-side edit, defeating self-service. Naming
# only the exclusions inverts that -- new services are covered automatically.
#
# Do not widen Match_Regex to kube.* across all namespaces: tenants differ in
# whether they want decoding, and a cluster-wide catch-all removes that choice.
# ---------------------------------------------------------------------------
CM_OUT="${DIR}/ds/configmap-conf-d-${DEPLOY_NAME}.yaml"

if [ ! -f "$CM_OUT" ]; then
cat > "$CM_OUT" <<YAML
# Generated by generate.sh — edit the exclusion list below, then re-apply.
# Regenerating will NOT overwrite this file once it exists.
#
# One filter pair covers the whole namespace. You do NOT list annotated
# services; you list the few that must be left alone.
#
# Filebeat processor          ->  Fluent Bit filter
#   copy_fields               ->  [FILTER] modify      + Copy <from> <to>
#   decode_json_fields ("")   ->  [FILTER] parser      + Parser json, Reserve_Data On
#   decode_json_fields ("x")  ->  ...then [FILTER] nest + Nest_under x
#   drop_fields               ->  [FILTER] record_modifier + Remove_key
#   add_fields                ->  [FILTER] record_modifier + Record
#   rename                    ->  [FILTER] modify      + Rename <old> <new>
apiVersion: v1
kind: ConfigMap
metadata:
  name: fluentbit-${DEPLOY_NAME}-conf-d
  namespace: ${NAMESPACE}
data:
  50-services.conf: |
    # One filter pair for the whole namespace. Services are NOT enumerated --
    # that does not scale and would make every new service a platform action.
    # Instead, name the few that must NOT be processed in the lookahead below.
    #
    # A plain-text service needs no exclusion: the parser filter only modifies
    # a record when the value actually parses as JSON.
    #
    # The lookahead is anchored right after "containers.", so an entry only
    # excludes pods whose name STARTS with it -- "log-generator" will not
    # accidentally exclude "notification-log-generator".
    #
    # Verified live 2026-11-04: annotated service 27593/27593 decoded,
    # excluded service 0/27677.

    [FILTER]
        Name        modify
        Match_Regex ^kube\.var\.log\.containers\.(?!(EXCLUDE-ME)-)[^_]+_${NAMESPACE}_
        Copy        message _message

    [FILTER]
        Name         parser
        Match_Regex  ^kube\.var\.log\.containers\.(?!(EXCLUDE-ME)-)[^_]+_${NAMESPACE}_
        Key_Name     message
        Parser       json
        Reserve_Data On

    # Replace EXCLUDE-ME with a pipe-separated list, e.g. (svc-a|svc-b).
    # Find candidates -- unannotated services that still emit JSON:
    #   kubectl get pods -n ${NAMESPACE} -o json | jq -r '.items[]
    #     | select(.metadata.annotations | to_entries[]? | .key
    #              | startswith("co.elastic.logs/processors") | not)
    #     | .metadata.name'
YAML
    CM_STATUS="created (contains only commented examples — harmless if applied as-is)"
else
    CM_STATUS="left unchanged — already exists, hand edits preserved"
fi

echo -e "\n${G}Generated:${Z}"
echo -e "  ${RBAC_OUT}"
echo -e "  ${K8S_OUT}"
echo -e "  ${CM_OUT}  ${B}[${CM_STATUS}]${Z}"
if $CLUSTER_WIDE; then
    echo -e "\n${B}Mode:${Z} cluster-wide (all nodes, all namespaces)"
fi
echo -e "\n${B}Step 1:${Z} Apply RBAC:"
echo -e "  kubectl apply -f ${RBAC_OUT}"
echo -e "\n${B}Step 2:${Z} Apply the per-service filters:"
echo -e "  kubectl apply -f ${CM_OUT}"
echo -e "\n${B}Step 3:${Z} Apply the DaemonSet:"
echo -e "  kubectl apply -f ${K8S_OUT}"
echo -e "\n${B}Verify filters loaded${Z} (they appear by name; absence means not loaded):"
echo -e "  kubectl -n ${NAMESPACE} port-forward <pod> 2020:2020"
echo -e "  curl -s localhost:2020/api/v1/metrics | jq '.filter | keys'"
