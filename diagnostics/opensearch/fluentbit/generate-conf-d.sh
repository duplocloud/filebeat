#!/usr/bin/env bash
# Generates the per-tenant conf.d ConfigMap from the Filebeat processor
# annotations actually present in the cluster. Pure filter, no Lua, no
# annotation changes -- tenants keep co.elastic.logs/* exactly as-is.
#
# Re-run whenever the annotation inventory changes (new service annotated,
# existing one updated) and re-apply. This is a snapshot, not a live read:
# a service annotated after the last run has no filter until this script
# runs again. For a zero-touch (fully dynamic) alternative see ARCHITECTURE.md.
#
# Usage:
#   ./generate-conf-d.sh <namespace>
#   kubectl apply -f ds/configmap-conf-d-<namespace>.yaml
#   kubectl -n <namespace> rollout restart ds/fluentbit-<namespace>-ds
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ -t 1 ]; then R='\033[0;31m' G='\033[0;32m' B='\033[1m' Z='\033[0m'
else R='' G='' B='' Z=''; fi
err() { echo -e "${R}Error:${Z} $1" >&2; exit 1; }

NAMESPACE="${1:-}"
[ -z "$NAMESPACE" ] && read -rp "Enter the K8s namespace (e.g. duploservices-acme): " NAMESPACE
NAMESPACE="$(echo "$NAMESPACE" | tr -d '[:space:]' | tr '[:upper:]' '[:lower:]')"
[ -z "$NAMESPACE" ] && err "Namespace cannot be empty."

command -v jq >/dev/null 2>&1 || err "jq is required."
command -v kubectl >/dev/null 2>&1 || err "kubectl is required."

# -----------------------------------------------------------------------
# Discover every pod carrying co.elastic.logs/processors.* and collapse
# to distinct pod-name prefixes (strip the trailing replicaset/pod hash).
# Matching on pod-name prefix, not container name: two different
# Deployments in the same namespace can share a container name, and a
# container-scoped match would decode both.
# -----------------------------------------------------------------------
SERVICES="$(kubectl get pods -n "$NAMESPACE" -o json 2>/dev/null | jq -r '
  .items[]
  | select(.metadata.annotations // {} | to_entries[]? | .key | startswith("co.elastic.logs/processors"))
  | (.metadata.labels.app // .metadata.name)
  | sub("-[0-9a-f]{6,10}-[a-z0-9]{5}$"; "")
  | sub("-[0-9a-f]{6,10}$"; "")
' | sort -u)"

if [ -z "$SERVICES" ]; then
    echo -e "${B}No annotated services found in ${NAMESPACE}.${Z}"
    echo "Nothing to generate — remove the ConfigMap or leave it absent (the DaemonSet mount is optional)."
    exit 0
fi

COUNT=$(echo "$SERVICES" | wc -l | tr -d ' ')
echo -e "${G}Found ${COUNT} annotated service(s) in ${NAMESPACE}:${Z}"
echo "$SERVICES" | sed 's/^/  /'

# Build the alternation: svc-a|svc-b|svc-c
ALTERNATION="$(echo "$SERVICES" | paste -sd'|' -)"

# Warn on prefix collisions: "payments-api" as an entry also matches a pod
# named "payments-api-legacy-...", because the alternation only anchors the
# START of the pod name, not the whole service name. Harmless if the longer
# name IS meant to be covered too; a bug if it is a different, unannotated
# service that happens to share a prefix.
while IFS= read -r svc; do
    collisions="$(echo "$SERVICES" | grep -v "^${svc}$" | grep "^${svc}-" || true)"
    if [ -n "$collisions" ]; then
        echo -e "${R}Warning:${Z} '${svc}' is a prefix of: $(echo "$collisions" | tr '\n' ' ')"
        echo "  Confirm these are meant to share this filter, or rename to avoid the collision."
    fi
done <<< "$SERVICES"

OUT="${DIR}/ds/configmap-conf-d-${NAMESPACE}.yaml"
cat > "$OUT" <<YAML
# Generated by generate-conf-d.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) from the
# co.elastic.logs/processors.* annotations present in ${NAMESPACE} at that
# moment. Re-run the script and re-apply after any annotation change —
# this file is NOT updated automatically.
#
# Services covered (${COUNT}):
$(echo "$SERVICES" | sed 's/^/#   /')
apiVersion: v1
kind: ConfigMap
metadata:
  name: fluentbit-${NAMESPACE}-conf-d
  namespace: ${NAMESPACE}
data:
  50-services.conf: |
    # Decode JSON only for the services above. Matched on pod-name prefix,
    # anchored right after "containers.", so this never catches an
    # unannotated service whose name happens to share a suffix.
    [FILTER]
        Name        modify
        Match_Regex ^kube\.var\.log\.containers\.(${ALTERNATION})-[^_]+_${NAMESPACE}_
        Copy        message _message

    [FILTER]
        Name         parser
        Match_Regex  ^kube\.var\.log\.containers\.(${ALTERNATION})-[^_]+_${NAMESPACE}_
        Key_Name     message
        Parser       json
        Reserve_Data On
YAML

echo -e "\n${G}Generated:${Z} ${OUT}"
echo -e "\n${B}Apply:${Z}"
echo -e "  kubectl apply -f ${OUT}"
echo -e "  kubectl -n ${NAMESPACE} rollout restart ds/fluentbit-${NAMESPACE}-ds"
echo -e "\n${B}Verify:${Z}"
echo -e "  kubectl -n ${NAMESPACE} get cm fluentbit-${NAMESPACE}-conf-d -o jsonpath='{.data.50-services\\.conf}' | grep Match_Regex"
echo -e "  curl -s localhost:2020/api/v1/metrics | jq '.filter | keys'"
